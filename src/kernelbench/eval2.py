import torch
import time
import numpy as np
from src.kernelbench.dataset import fetch_kernelbench_sample, fetch_kernelbench_dataset


def evaluate_kernel(original_code: str, llm_code: str, warmup_runs: int = 20, num_runs: int = 100):
    """
    Compile, run, and profile CUDA kernel generated by LLM.
    
    Args:
        original_code: Reference implementation code
        llm_code: LLM-generated CUDA kernel code
        warmup_runs: Number of warmup iterations (default: 20)
        num_runs: Number of timed runs for profiling (default: 100)
    
    Returns:
        dict with compilation status, correctness, and performance metrics
    """
    device = torch.device("cuda:0")
    result = {
        "compiled": False,
        "executed": False,
        "correct": False,
        "speedup": None,
        "ref_time_ms": None,
        "new_time_ms": None,
        "ref_time_std_ms": None,
        "new_time_std_ms": None,
        "ref_time_min_ms": None,
        "new_time_min_ms": None,
        "error": None
    }
    
    # Step 1: Compile and execute the original (reference) code
    print("=" * 60)
    print("Compiling reference implementation...")
    orig_ctx = {}
    try:
        exec(original_code, orig_ctx)
    except Exception as e:
        result["error"] = f"Reference compilation failed: {e}"
        return result
    
    # Step 2: Compile and execute the LLM-generated code
    print("Compiling LLM-generated CUDA kernel...")
    print("(This will take 10-30 seconds on first run...)")
    llm_ctx = {}
    try:
        exec(llm_code, llm_ctx)
        result["compiled"] = True
        print("✓ Compilation successful!")
    except Exception as e:
        result["error"] = f"LLM code compilation failed: {e}"
        print(f"✗ Compilation failed: {e}")
        return result
    
    # Step 3: Get Model classes and input generators
    try:
        ModelRef = orig_ctx.get("Model")
        ModelNew = llm_ctx.get("ModelNew")
        get_inputs = orig_ctx.get("get_inputs")
        get_init_inputs = orig_ctx.get("get_init_inputs")
        
        if not all([ModelRef, ModelNew, get_inputs, get_init_inputs]):
            missing = []
            if not ModelRef: missing.append("Model")
            if not ModelNew: missing.append("ModelNew")
            if not get_inputs: missing.append("get_inputs")
            if not get_init_inputs: missing.append("get_init_inputs")
            result["error"] = f"Missing required objects: {missing}"
            return result
    except Exception as e:
        result["error"] = f"Failed to extract functions: {e}"
        return result
    
    # Step 4: Create models and prepare inputs
    print("\nPreparing models and inputs...")
    try:
        init_inputs = get_init_inputs()
        inputs = get_inputs()
        
        # Move to GPU and set to eval mode
        model_ref = ModelRef(*init_inputs).to(device).eval()
        model_new = ModelNew(*init_inputs).to(device).eval()
        
        # Move inputs to GPU and ensure contiguous layout
        inputs_gpu = []
        for inp in inputs:
            if isinstance(inp, torch.Tensor):
                tensor = inp.to(device)
                if not tensor.is_contiguous():
                    print(f"⚠ Warning: Input tensor not contiguous, making contiguous")
                    tensor = tensor.contiguous()
                inputs_gpu.append(tensor)
            else:
                inputs_gpu.append(inp)
        
        result["executed"] = True
    except Exception as e:
        result["error"] = f"Model initialization failed: {e}"
        print(f"✗ Execution failed: {e}")
        return result
    
    # Step 5: Correctness check
    print("\nVerifying correctness...")
    try:
        with torch.inference_mode():
            output_ref = model_ref(*inputs_gpu)
            output_new = model_new(*inputs_gpu)
            torch.cuda.synchronize()
            
            # Compare outputs
            if isinstance(output_ref, torch.Tensor) and isinstance(output_new, torch.Tensor):
                max_diff = torch.max(torch.abs(output_ref - output_new)).item()
                mean_diff = torch.mean(torch.abs(output_ref - output_new)).item()
                
                # Use tighter tolerances
                is_correct = torch.allclose(output_ref, output_new, atol=1e-5, rtol=1e-3)
                
                if is_correct:
                    result["correct"] = True
                    print(f"✓ Outputs match!")
                    print(f"  Max absolute diff: {max_diff:.2e}")
                    print(f"  Mean absolute diff: {mean_diff:.2e}")
                else:
                    result["error"] = f"Output mismatch (max: {max_diff:.2e}, mean: {mean_diff:.2e})"
                    print(f"✗ Output mismatch")
                    print(f"  Max absolute diff: {max_diff:.2e}")
                    print(f"  Mean absolute diff: {mean_diff:.2e}")
                    
                    # Additional debugging info
                    ref_norm = torch.norm(output_ref).item()
                    new_norm = torch.norm(output_new).item()
                    print(f"  Reference norm: {ref_norm:.2e}")
                    print(f"  LLM kernel norm: {new_norm:.2e}")
                    return result
            else:
                result["error"] = "Non-tensor outputs not supported yet"
                return result
                
    except Exception as e:
        result["error"] = f"Correctness check failed: {e}"
        print(f"✗ Correctness check failed: {e}")
        return result
    
    # Step 6: Performance profiling using CUDA events
    print(f"\nProfiling performance ({warmup_runs} warmup + {num_runs} timed runs)...")
    try:
        with torch.inference_mode():
            # Warmup runs
            print("Running warmup iterations...")
            for i in range(warmup_runs):
                _ = model_ref(*inputs_gpu)
                _ = model_new(*inputs_gpu)
                if i == 0 or i == warmup_runs - 1:
                    torch.cuda.synchronize()  # Sync on first and last
            torch.cuda.synchronize()
            print("✓ Warmup complete")
            
            # Create CUDA events for precise GPU timing
            start_event = torch.cuda.Event(enable_timing=True)
            end_event = torch.cuda.Event(enable_timing=True)
            
            # Timed runs for reference
            print("Timing reference implementation...")
            ref_times = []
            for _ in range(num_runs):
                start_event.record()
                _ = model_ref(*inputs_gpu)
                end_event.record()
                torch.cuda.synchronize()
                ref_times.append(start_event.elapsed_time(end_event))  # milliseconds
            
            # Timed runs for LLM kernel
            print("Timing LLM kernel...")
            new_times = []
            for _ in range(num_runs):
                start_event.record()
                _ = model_new(*inputs_gpu)
                end_event.record()
                torch.cuda.synchronize()
                new_times.append(start_event.elapsed_time(end_event))  # milliseconds
            
            # Calculate statistics
            ref_times = np.array(ref_times)
            new_times = np.array(new_times)
            
            ref_median = np.median(ref_times)
            new_median = np.median(new_times)
            ref_mean = np.mean(ref_times)
            new_mean = np.mean(new_times)
            ref_std = np.std(ref_times)
            new_std = np.std(ref_times)
            ref_min = np.min(ref_times)
            new_min = np.min(new_times)
            
            speedup_median = ref_median / new_median
            speedup_mean = ref_mean / new_mean
            speedup_min = ref_min / new_min
            
            result["speedup"] = speedup_median
            result["ref_time_ms"] = ref_median
            result["new_time_ms"] = new_median
            result["ref_time_std_ms"] = ref_std
            result["new_time_std_ms"] = new_std
            result["ref_time_min_ms"] = ref_min
            result["new_time_min_ms"] = new_min
            
            print(f"\n{'Results:':<20}")
            print(f"{'Reference:':<20}")
            print(f"  {'Median:':<18} {ref_median:.3f} ms")
            print(f"  {'Mean:':<18} {ref_mean:.3f} ms")
            print(f"  {'Std Dev:':<18} {ref_std:.3f} ms")
            print(f"  {'Min:':<18} {ref_min:.3f} ms")
            print(f"\n{'LLM Kernel:':<20}")
            print(f"  {'Median:':<18} {new_median:.3f} ms")
            print(f"  {'Mean:':<18} {new_mean:.3f} ms")
            print(f"  {'Std Dev:':<18} {new_std:.3f} ms")
            print(f"  {'Min:':<18} {new_min:.3f} ms")
            print(f"\n{'Speedup:':<20}")
            print(f"  {'Median-based:':<18} {speedup_median:.2f}x")
            print(f"  {'Mean-based:':<18} {speedup_mean:.2f}x")
            print(f"  {'Min-based:':<18} {speedup_min:.2f}x")
            
            # Check for high variance (potential instability)
            if ref_std / ref_mean > 0.05:
                print(f"\n⚠ Warning: High variance in reference timings ({ref_std/ref_mean*100:.1f}%)")
            if new_std / new_mean > 0.05:
                print(f"⚠ Warning: High variance in LLM kernel timings ({new_std/new_mean*100:.1f}%)")
            
    except Exception as e:
        result["error"] = f"Profiling failed: {e}"
        print(f"✗ Profiling failed: {e}")
        return result
    
    return result


